'use strict';
const { chromium, testOutput } = require('../helpers/browser.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const { managementFixture } = await import('../helpers/management-fixture.js');
  const { totpCode } = await import('../../backend/management/totp.js');
  const f = await managementFixture({ editable: false, officialDefaults: false }); let browser;
  try {
    const other = await f.login();
    browser = await chromium.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await context.request.post(f.base + '/api/login', { data: { username: f.username, password: f.password } });
    await page.goto(f.base + '/#login-logs');
    await page.waitForFunction(() => document.getElementById('login-log-status').textContent.includes('实时更新'));
    const open = async () => {
      await page.locator('#account-security').click();
      await page.waitForFunction(() => !document.getElementById('account-username-button').disabled);
      await page.locator('#account-username-button').click();
    };
    await open();
    assert.equal(await page.locator('#security-username').textContent(), '当前用户名：admin');
    assert.equal(await page.locator('#username-code-field').isVisible(), false);
    await page.locator('#username-new').fill(f.username);
    await page.locator('#username-password').fill(f.password);
    await page.locator('#username-submit').click();
    assert.equal(await page.locator('#username-new').evaluate(input => input.validity.customError), true);
    await page.locator('#username-new').fill('新管理员');
    await page.locator('#username-password').fill('wrong-password');
    await page.locator('#username-submit').click(); await page.locator('#username-error').waitFor();
    assert.match(await page.locator('#username-error').textContent(), /密码不正确/);
    await page.locator('#username-password-reveal').click();
    assert.equal(await page.locator('#username-password').getAttribute('type'), 'text');
    await page.locator('#account-password-button').click();
    assert.equal(await page.locator('#username-section').isVisible(), false);
    assert.equal(await page.locator('#username-password').inputValue(), '');
    await page.locator('#account-username-button').click();
    assert.equal(await page.locator('#username-password').getAttribute('type'), 'password');
    await page.locator('#username-new').fill('新管理员'); await page.locator('#username-password').fill(f.password);
    const previousCookie = (await context.cookies()).find(cookie => cookie.name === 'palbox_session').value;
    await page.locator('#username-submit').click();
    await page.waitForFunction(() => document.getElementById('security-username').textContent === '当前用户名：新管理员' && !document.getElementById('username-fields').disabled);
    assert.notEqual((await context.cookies()).find(cookie => cookie.name === 'palbox_session').value, previousCookie);
    assert.equal((await f.request('/api/settings', { headers: { Cookie: other.cookie } })).status, 401);
    assert.equal(await page.locator('#username-new').inputValue(), '');
    assert.equal(await page.locator('#username-password').inputValue(), '');
    await page.waitForFunction(() => document.getElementById('login-log-content').textContent.includes('管理员用户名已修改'));
    assert.equal((await page.locator('#login-log-status').textContent()).includes('登录已失效'), false);
    const output = testOutput('username'); await fs.mkdir(output, { recursive: true });
    await page.screenshot({ path: path.join(output, 'desktop.png') });
    console.log('PASS 用户名表单、当前密码校验、小眼睛、切换清理、改名与会话和日志连接更新');

    await page.locator('#account-totp-button').click();
    await page.locator('#security-password').fill(f.password); await page.locator('#security-submit').click();
    await page.locator('#security-setup').waitFor();
    assert.equal(await page.locator('#security-account').textContent(), 'PalBox: 新管理员');
    const secret = await page.locator('#security-secret').textContent();
    await page.locator('#security-code').fill(totpCode(secret, Math.floor(Date.now() / 30000) - 1));
    await page.locator('#security-submit').click(); await page.locator('#security-recovery').waitFor();
    const codes = (await page.locator('#security-recovery-codes').textContent()).split('\n');
    await page.locator('#security-saved').click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#mobile-menu').click(); await open();
    assert.equal(await page.locator('#username-code-field').isVisible(), true);
    await page.locator('#username-new').fill('移动端管理员'); await page.locator('#username-password').fill(f.password);
    await page.locator('#username-code').fill('bad'); await page.locator('#username-submit').click();
    await page.locator('#username-error').waitFor();
    assert.equal(f.manager.settings.admin.username, '新管理员');
    await page.locator('#username-code').fill(codes[0]); await page.locator('#username-submit').click();
    await page.waitForFunction(() => document.getElementById('security-username').textContent === '当前用户名：移动端管理员' && !document.getElementById('username-fields').disabled);
    assert.match(await page.locator('#security-status').textContent(), /剩余 9 个恢复码/);
    assert.equal(f.manager.settings.admin.totp.secret, secret);
    assert.equal(await page.locator('#username-code').inputValue(), '');
    assert.equal(await page.locator('#account-security-dialog').evaluate(el => el.scrollWidth <= el.clientWidth), true);
    await page.screenshot({ path: path.join(output, 'mobile.png') });
    await page.locator('#manager-logout').click(); await page.waitForURL('**/login.html');
    const login = async username => {
      await page.locator('#login-username').fill(username); await page.locator('#login-password').fill(f.password); await page.locator('#login-submit').click();
    };
    await login(f.username); await page.locator('#login-error').waitFor();
    await login('移动端管理员'); await page.locator('#login-totp-step').waitFor();
    await page.locator('#login-use-recovery').click(); await page.locator('#login-code').fill(codes[1]); await page.locator('#login-submit').click();
    await page.waitForURL(f.base + '/');
    assert.deepEqual(errors, []);
    console.log('PASS 手机端二次验证改名、恢复码消费、保留验证器绑定及使用新用户名登录');
  } finally { await browser?.close(); await f.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
