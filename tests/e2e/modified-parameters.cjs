'use strict';
const { chromium, testOutput } = require('../helpers/browser.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const { managementFixture } = await import('../helpers/management-fixture.js');
  const { applyManagedChanges, parse, decodeString } = await import('../../shared/domain/config.js');
  const f = await managementFixture();
  let browser;
  try {
    await f.login(); await f.task('install'); await f.task('start');
    const snapshot = f.manager.store.snapshot();
    const active = snapshot.workspace.profiles.find(profile => profile.id === snapshot.workspace.activeId);
    active.source = applyManagedChanges(active.source, new Map([
      ['ExpRate', '2.5'], ['PalCaptureRate', '3'], ['AdminPassword', '"modified-private-password"'],
      ['ServerName', '"<img src=x onerror=alert(1)>"'], ['UnknownFlag', '(Enabled=True,Rate=7)'],
      ['bIsPvP', 'True'], ['DeathPenalty', 'None']
    ]));
    await f.manager.store.update(snapshot.workspace, snapshot.revision);
    browser = await chromium.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
    await context.request.post(f.base + '/api/login', { data: { username: f.username, password: f.password } });
    const page = await context.newPage();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(f.base + '/#configuration');
    const changes = page.locator('#modified-parameters-dialog');
    const card = key => changes.locator(`[data-modified-key="${key}"]`);
    const input = key => card(key).locator('[data-diff-value="current"] input, [data-diff-value="current"] select');
    const stored = key => parse(f.manager.store.active().source).entries.find(entry => entry.key === key)?.raw;
    const saved = () => page.waitForFunction(() => document.querySelector('#modified-parameters-save').textContent === '已保存');
    const gameConfig = path.join(f.directory, 'server/Pal/Saved/Config/LinuxServer/PalWorldSettings.ini');
    const originalGameConfig = await fs.readFile(gameConfig, 'utf8');
    const output = testOutput('modified-parameters'); await fs.mkdir(output, { recursive: true });
    await page.locator('#modified-summary').waitFor();
    await page.screenshot({ path: path.join(output, 'desktop-summary.png'), animations: 'disabled' });
    await page.locator('#modified-summary').click();
    await card('PalCaptureRate').locator('.pending-badge').waitFor();
    assert.equal(await page.title(), 'PalBox · 配置管理 · 配置编辑');
    assert.ok(page.url().endsWith('/#configuration'), '查看修改不会跳转页面');
    assert.equal(await page.locator('#modified-summary').count(), 1, '恢复已修改统计卡');
    assert.equal(await page.locator('#configuration-profiles').isVisible(), false);
    assert.equal(await page.locator('#nav-configuration-changes').count(), 0);
    let count = Number(await page.locator('#change-count').textContent());
    assert.equal(Number(await page.locator('#modified-summary-count').textContent()), count);
    assert.equal(await changes.locator('[data-modified-key]').count(), count);
    assert.match(await card('ExpRate').locator('[data-diff-value="original"]').textContent(), /1\.000000/);
    assert.equal(await input('ExpRate').inputValue(), '2.500000');
    assert.match(await card('UnknownFlag').locator('[data-diff-value="original"]').textContent(), /未设置/);
    assert.equal(await input('UnknownFlag').inputValue(), '(Enabled=True,Rate=7)');
    assert.equal(await changes.locator('img').count(), 0);
    const password = card('AdminPassword').locator('[data-diff-value="current"] input');
    assert.equal(await password.getAttribute('type'), 'password');
    await card('AdminPassword').locator('[data-diff-value="current"] button').click();
    assert.equal(await password.getAttribute('type'), 'text');
    const search = page.locator('#modified-parameters-search');
    await search.fill('捕捉');
    assert.equal(await changes.locator('[data-modified-key]').count(), 1);
    assert.match(await changes.textContent(), /帕鲁捕捉倍率/);
    await search.fill('modified-private-password');
    assert.equal(await changes.locator('[data-modified-key]').count(), 0, '搜索不匹配密码值');
    await search.fill('');
    await input('ExpRate').fill('broken');
    assert.equal(await input('ExpRate').getAttribute('aria-invalid'), 'true');
    assert.match(await card('ExpRate').locator('.field-error').textContent(), /有效数字/);
    assert.equal(Number(stored('ExpRate')), 2.5, '无效输入保留上一次有效值');
    await input('ExpRate').fill('1');
    await saved();
    assert.equal(await input('ExpRate').evaluate(el => el === document.activeElement), true, '临时等于原值时不移除正在编辑的输入框');
    await input('ExpRate').pressSequentially('.75');
    await saved();
    assert.equal(await input('ExpRate').inputValue(), '1.75');
    assert.equal(Number(stored('ExpRate')), 1.75);
    await input('UnknownFlag').fill('(Enabled=False,Rate=9)');
    await saved();
    assert.equal(stored('UnknownFlag'), '(Enabled=False,Rate=9)');
    assert.equal(await input('ExpRate').inputValue(), '1.750000', '失焦时格式化数字');
    await input('DeathPenalty').selectOption('All');
    await saved();
    assert.equal(stored('DeathPenalty'), 'All');
    await input('bIsPvP').selectOption('False');
    await input('UnknownFlag').click();
    await saved();
    assert.equal(await card('bIsPvP').count(), 0, '改回基准值后移除这一项');
    count--;
    await password.fill('edited-private-password');
    await saved();
    assert.equal(decodeString(stored('AdminPassword')), 'edited-private-password');
    assert.equal(await changes.locator('img').count(), 0);

    const reset = card('PalCaptureRate').locator('[data-reset-field="PalCaptureRate"]');
    await reset.click();
    await page.locator('#dialog-cancel').click();
    assert.equal(Number(await input('PalCaptureRate').inputValue()), 3);
    await input('ExpRate').fill('broken');
    await reset.click();
    const restoredResponse = page.waitForResponse(response => response.url().endsWith('/api/workspace') && response.request().method() === 'PUT');
    await page.locator('#dialog-confirm').click();
    assert.equal((await restoredResponse).ok(), true);
    await card('PalCaptureRate').waitFor({ state: 'detached' });
    assert.equal(await search.evaluate(el => el === document.activeElement), true, '恢复后焦点仍在弹窗内');
    assert.equal(Number(stored('PalCaptureRate')), 1, '恢复的只是当前参数');
    assert.equal(await input('ExpRate').inputValue(), 'broken', '恢复其他项保留无效输入');
    assert.equal(await input('ExpRate').getAttribute('aria-invalid'), 'true');
    count--;
    await input('ExpRate').fill('4.25');
    await saved();
    assert.equal(Number(stored('ExpRate')), 4.25);
    assert.equal(await changes.locator('[data-modified-key]').count(), count);
    assert.equal(Number(await page.locator('#change-count').textContent()), count);
    assert.equal(Number(await page.locator('#modified-summary-count').textContent()), count, '统计卡随单项恢复同步更新');

    await page.route('**/api/workspace', async route => {
      if (route.request().method() !== 'PUT') return route.continue();
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '测试保存失败' }) });
    });
    await input('ExpRate').fill('5.25');
    await page.waitForFunction(() => document.querySelector('#modified-parameters-save').textContent === '保存失败');
    assert.equal(await input('ExpRate').inputValue(), '5.25', '保存失败仍保留编辑内容');
    assert.equal(Number(stored('ExpRate')), 4.25);
    await page.unroute('**/api/workspace');
    await input('ExpRate').fill('6.25');
    await saved();
    assert.equal(Number(stored('ExpRate')), 6.25);
    assert.equal(await fs.readFile(gameConfig, 'utf8'), originalGameConfig, '弹窗编辑和恢复不直接改写游戏配置');
    await page.screenshot({ path: path.join(output, 'desktop.png'), animations: 'disabled' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'mobile.png'), animations: 'disabled' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('#modified-parameters-done').click();
    await page.waitForFunction(() => !document.querySelector('#modified-parameters-list input'));
    assert.equal(await changes.locator('input[type="password"], input[type="text"]').count(), 0);
    assert.equal(await page.locator('#modified-summary').evaluate(el => el.getBoundingClientRect().width > 0), true);
    await page.screenshot({ path: path.join(output, 'mobile-summary.png'), animations: 'disabled' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('#modified-summary').focus();
    await page.locator('#modified-summary').press('Enter');
    await card('ExpRate').waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#modified-summary').evaluate(el => el === document.activeElement), true, '关闭后焦点回到统计卡');
    await page.locator('#search').fill('ExpRate');
    assert.equal(await page.locator('#field-ExpRate').inputValue(), '6.250000', '关闭后编辑页面已同步');
    await page.locator('#search').fill('');
    await page.locator('#show-modified-parameters').click();
    await card('ExpRate').locator('.pending-badge').waitFor();
    await page.locator('#modified-parameters-close').click();
    const applied = await f.task('apply', { revision: f.manager.store.revision, profileId: active.id });
    assert.equal(applied.state, 'succeeded');
    await page.locator('#show-modified-parameters').click();
    await card('ExpRate').waitFor();
    await page.waitForFunction(() => !document.querySelector('#modified-parameters-dialog .pending-badge'));
    assert.equal(await changes.locator('[data-modified-key]').count(), count, '应用后仍保留相对初始配置的全部修改');
    await page.reload(); await page.locator('#show-modified-parameters').click(); await card('ExpRate').waitFor();
    assert.equal(await changes.locator('[data-modified-key]').count(), count);
    const restored = f.manager.store.snapshot();
    const working = restored.workspace.profiles.find(profile => profile.id === restored.workspace.activeId);
    working.source = working.initialSource;
    await f.manager.store.update(restored.workspace, restored.revision);
    await page.reload(); await page.locator('#show-modified-parameters').click();
    await page.locator('#modified-parameters-empty').waitFor();
    assert.equal(await changes.locator('[data-modified-key]').count(), 0);
    assert.equal(await page.locator('#modified-summary-count').textContent(), '0');
    assert.match(await page.locator('#modified-parameters-empty').textContent(), /没有相对初始基准的修改/);
    assert.deepEqual(errors, []);
    console.log('PASS 已修改统计卡与悬浮按钮打开同一弹窗、数量同步、键盘访问和焦点恢复；直接编辑、自动保存、校验、单项恢复、失败保留输入、编辑页同步、应用前不写入游戏、搜索、密码遮挡、刷新恢复和手机布局');
  } finally { await browser?.close(); await f.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
