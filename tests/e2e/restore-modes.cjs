const { chromium, testOutput } = require('../helpers/browser.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const { managementFixture } = await import('../helpers/management-fixture.js');
  const { nativeBackupFixture } = await import('../helpers/native-backup-fixture.js');
  const f = await managementFixture();
  let browser;
  try {
    await f.login();
    assert.equal((await f.task('install')).state, 'succeeded');
    await nativeBackupFixture(f.runtime.saved, { worldId: 'SAVED_WORLD' });
    const id = await f.manager.backup('manual');
    const current = await nativeBackupFixture(f.runtime.saved, { worldId: 'CURRENT_WORLD' });
    await fs.writeFile(path.join(current.world, 'Level.sav'), 'before-restore');
    await fs.writeFile(path.join(current.world, 'old-only.sav'), 'remove');
    browser = await chromium.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    await context.request.post(f.base + '/api/login', { data: { username: f.username, password: f.password } });
    const page = await context.newPage();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(f.base + '/#saves/archives');
    const restore = () => page.locator('[data-backup-category="manual"] .backup-row').getByRole('button', { name: '恢复', exact: true });
    await restore().click();
    await page.locator('#save-import-details').waitFor();
    assert.equal(await page.locator('#save-import-title').textContent(), '导入与恢复');
    assert.equal(await page.locator('#save-import-drop').isVisible(), false);
    const details = await page.locator('#save-import-details').textContent();
    assert.match(details, /检测到存档和配置/);
    assert.match(details, /SAVED_WORLD/);
    assert.match(details, /CURRENT_WORLD/);
    assert.match(details, /SaveGames\/0\/CURRENT_WORLD/);
    assert.match(details, /游戏默认配置.*当前选中/);
    assert.equal(await page.getByRole('button', { name: '完整恢复', exact: true }).count(), 0);
    assert.equal(f.manager.tasks.filter(task => task.action === 'restore').length, 0);
    await page.locator('#save-import-cancel').click();
    assert.equal(await fs.readFile(path.join(current.world, 'Level.sav'), 'utf8'), 'before-restore');
    await restore().click();
    await page.locator('#save-import-details').waitFor();
    const output = testOutput('unified-restore');
    await fs.mkdir(output, { recursive: true });
    await page.screenshot({ path: path.join(output, 'mobile.png') });
    assert.equal(await page.locator('#save-import-dialog').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth), true);
    const submitted = page.waitForResponse(response => response.url().endsWith('/api/tasks') && response.request().method() === 'POST');
    await page.locator('#save-import-confirm').click();
    const response = await submitted;
    assert.equal(response.status(), 202);
    const payload = response.request().postDataJSON();
    assert.equal(payload.mode, undefined);
    assert.equal(payload.id, id);
    assert.equal(payload.targetWorldId, 'CURRENT_WORLD');
    await f.manager.operation;
    assert.equal(f.manager.tasks[0].state, 'succeeded', f.manager.tasks[0].message);
    assert.equal(await f.manager.targetWorld(), 'CURRENT_WORLD');
    assert.equal(await fs.readFile(path.join(current.world, 'Level.sav'), 'utf8'), 'current-world');
    await assert.rejects(fs.access(path.join(current.world, 'old-only.sav')), { code: 'ENOENT' });
    assert.equal(f.manager.store.active().name, '游戏默认配置');
    await page.locator('#save-import-dialog').waitFor({ state: 'hidden' });
    await fs.writeFile(path.join(current.world, 'Level.sav'), 'keep-current-world');
    const sourceWorld = path.join(f.runtime.saved, 'SaveGames/0/SAVED_WORLD');
    await fs.writeFile(path.join(sourceWorld, 'Level.sav'), 'replace-source-world');
    await restore().click();
    await page.locator('#save-import-details').waitFor();
    assert.equal(await page.locator('#save-import-mode').inputValue(), 'world');
    const detected = page.waitForResponse(response => response.url().endsWith('/api/restore-preview'));
    await page.locator('#save-import-mode').selectOption('source-world');
    assert.equal((await detected).status(), 200);
    await page.locator('#save-import-details').waitFor();
    const byId = await page.locator('#save-import-details').textContent();
    assert.match(byId, /SaveGames\/0\/SAVED_WORLD/);
    assert.match(byId, /覆盖目标世界/);
    assert.match(byId, /切换到该世界/);
    assert.equal(await f.manager.targetWorld(), 'CURRENT_WORLD');
    await page.screenshot({ path: path.join(output, 'mobile-world-id.png') });
    assert.equal(await page.locator('#save-import-dialog').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth), true);
    const sourceSubmitted = page.waitForResponse(response => response.url().endsWith('/api/tasks') && response.request().method() === 'POST');
    await page.locator('#save-import-confirm').click();
    const sourceResponse = await sourceSubmitted;
    assert.equal(sourceResponse.status(), 202);
    assert.equal(sourceResponse.request().postDataJSON().mode, 'source-world');
    assert.equal(sourceResponse.request().postDataJSON().targetWorldId, 'SAVED_WORLD');
    await f.manager.operation;
    assert.equal(f.manager.tasks[0].state, 'succeeded', f.manager.tasks[0].message);
    assert.equal(await f.manager.targetWorld(), 'SAVED_WORLD');
    assert.equal(await fs.readFile(path.join(sourceWorld, 'Level.sav'), 'utf8'), 'current-world');
    assert.equal(await fs.readFile(path.join(current.world, 'Level.sav'), 'utf8'), 'keep-current-world');
    assert.deepEqual(errors, []);
    console.log('PASS 默认恢复到当前世界；切换按备份世界 ID 恢复后重新预览目标，确认后切换加载世界，保留其他世界；手机布局正常');
  } finally { await browser?.close(); await f.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
