'use strict';
const { chromium, testOutput } = require('../helpers/browser.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const { managementFixture } = await import('../helpers/management-fixture.js');
  const { parse, serialize } = await import('../../shared/domain/config.js');
  const f = await managementFixture();
  let browser;
  try {
    await f.login(); await f.task('install'); await f.task('start');
    const snapshot = f.manager.store.snapshot();
    const active = snapshot.workspace.profiles.find(profile => profile.id === snapshot.workspace.activeId);
    const serverName = '<img src=x onerror=alert(1)> 待应用名称';
    active.source = serialize(parse(active.source), new Map([
      ['ExpRate', '2.5'], ['ServerName', JSON.stringify(serverName)], ['AdminPassword', '"pending-private-password"']
    ]));
    active.initialSource = serialize(parse(active.initialSource), new Map([['ExpRate', '7']]));
    await f.manager.store.update(snapshot.workspace, snapshot.revision);
    browser = await chromium.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    await context.request.post(f.base + '/api/login', { data: { username: f.username, password: f.password } });
    const page = await context.newPage();
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (new URL(request.url()).pathname === '/api/configuration-diff') requests.push(request); });
    await page.goto(f.base + '/#configuration');
    const button = page.locator('#show-pending-config');
    await button.waitFor();
    await page.locator('#fields-grid [data-editor-key="ServerName"] .pending-badge').waitFor();
    assert.equal(await page.locator('#fields-grid [data-editor-key="RESTAPIPort"] .pending-badge').count(), 0);
    assert.equal(await button.evaluate(node => node.nextElementSibling.dataset.action), 'apply');
    assert.equal(await button.evaluate(node => node.getBoundingClientRect().height), await page.locator('[data-action="apply"]').evaluate(node => node.getBoundingClientRect().height));
    const dock = page.locator('#configuration-actions');
    const beforeScroll = await dock.boundingBox();
    await page.evaluate(() => scrollTo(0, document.body.scrollHeight));
    const afterScroll = await dock.boundingBox();
    assert.equal(Math.round(afterScroll.y), Math.round(beforeScroll.y), '滚动后配置操作栏仍固定在视口底部');
    assert.ok((await page.locator('#view-form .form-note').boundingBox()).y + (await page.locator('#view-form .form-note').boundingBox()).height < afterScroll.y, '滚到页面末尾后正文不会被操作栏遮挡');
    await page.evaluate(() => scrollTo(0, 0));
    await page.locator('#search').fill('ExpRate');
    const pendingField = page.locator('#fields-grid [data-editor-key="ExpRate"] .pending-badge');
    await pendingField.waitFor();
    const editor = page.locator('#field-ExpRate');
    const cleared = page.waitForResponse(response => new URL(response.url()).pathname === '/api/configuration-diff' && response.ok());
    await editor.fill('1'); await cleared;
    await pendingField.waitFor({ state: 'hidden' });
    assert.equal(await editor.evaluate(node => node === document.activeElement), true, '更新标记不会重建输入控件或抢走焦点');
    await editor.fill('2.5'); await pendingField.waitFor();
    await page.locator('#editor-mode-advanced').click();
    await page.locator('#parameter-rows [data-editor-key="ExpRate"] .pending-badge').waitFor();
    await page.locator('#editor-mode-form').click(); await pendingField.waitFor();
    await page.waitForFunction(() => !document.getElementById('refresh-status').disabled && document.querySelector('#fields-grid [data-editor-key="ExpRate"] .pending-badge'));
    const output = testOutput('pending-configuration'); await fs.mkdir(output, { recursive: true });
    await page.screenshot({ path: path.join(output, 'toolbar-desktop.png') });
    await button.click();
    const dialog = page.locator('#pending-config-dialog');
    const card = key => dialog.locator(`[data-configuration-key="${key}"]`);
    const value = (key, kind) => card(key).locator(`[data-diff-value="${kind}"]`);
    await card('ExpRate').waitFor();
    const openedRequests = requests.length;
    assert.equal(await dialog.locator('[data-configuration-key]').count(), 3);
    assert.match(await value('ExpRate', 'running').textContent(), /1\.000000/);
    assert.match(await value('ExpRate', 'written').textContent(), /1\.000000/);
    assert.match(await value('ExpRate', 'desired').textContent(), /2\.500000/);
    assert.match(await card('ExpRate').textContent(), /待写入.*待重启/s);
    assert.equal(await value('ExpRate', 'desired').locator('.subtle-tag').count(), 2, '状态标记紧跟待应用值');
    assert.equal(await value('ExpRate', 'written').locator('.subtle-tag').count(), 0);
    assert.match(await value('ServerName', 'desired').textContent(), /<img src=x/);
    assert.equal(await dialog.locator('img').count(), 0);
    const password = value('AdminPassword', 'desired').locator('input');
    assert.equal(await password.getAttribute('type'), 'password');
    assert.equal(await password.inputValue(), 'pending-private-password');
    await value('AdminPassword', 'desired').locator('button').click();
    assert.equal(await password.getAttribute('type'), 'text');
    await value('AdminPassword', 'desired').locator('button').click();
    await page.screenshot({ path: path.join(output, 'desktop.png') });
    await page.locator('#pending-config-done').click();
    await page.waitForFunction(() => !document.querySelector('#pending-config-list input'));
    assert.equal(await dialog.locator('input').count(), 0, '关闭窗口清除密码值');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'toolbar-mobile.png'), animations: 'disabled' });
    await button.click(); await card('ExpRate').waitFor();
    assert.equal(requests.length, openedRequests + 1, '重新打开差异时读取一次，窗口内的交互不重复请求');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth), true);
    await page.screenshot({ path: path.join(output, 'mobile.png') });
    const undo = key => card(key).locator(`[data-undo-configuration="${key}"]`);
    const stored = key => parse(f.manager.store.active().source).entries.find(entry => entry.key === key)?.raw;
    const originalFile = await fs.readFile(f.runtime.config, 'utf8');
    await page.route('**/api/workspace', route => route.request().method() === 'PUT'
      ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '测试保存失败' }) })
      : route.continue());
    await undo('ExpRate').click();
    await page.locator('#pending-config-error').waitFor();
    assert.equal(Number(stored('ExpRate')), 2.5, '保存失败时不改变服务器上的配置');
    await page.unroute('**/api/workspace');
    await undo('ExpRate').click();
    await card('ExpRate').waitFor({ state: 'detached' });
    assert.equal(Number(stored('ExpRate')), 1, '恢复本次启动值，而非初始基准 7');
    assert.equal(stored('ServerName'), JSON.stringify(serverName), '撤销只影响当前项');
    assert.equal(await dialog.locator('[data-configuration-key]').count(), 2);
    assert.equal(await fs.readFile(f.runtime.config, 'utf8'), originalFile, '撤销不直接改写游戏文件');
    assert.equal(f.runtime.runningSource.includes('ExpRate=1.000000'), true, '撤销不重启游戏服');
    await page.screenshot({ path: path.join(output, 'mobile-undo.png') });
    await page.locator('#pending-config-done').click();
    const applied = await f.task('apply', { revision: f.manager.store.revision, profileId: active.id });
    assert.equal(applied.state, 'succeeded');
    await button.waitFor({ state: 'hidden' });
    await page.waitForFunction(() => !document.querySelector('#fields-grid .pending-badge, #parameter-rows .pending-badge'));
    assert.equal(await page.locator('#fields-grid .pending-badge, #parameter-rows .pending-badge').count(), 0);
    const source = await fs.readFile(f.runtime.config, 'utf8');
    await fs.writeFile(f.runtime.config, '; formatting only\r\n' + source.replace(/\r?\n/g, '\r\n'));
    const actual = await f.manager.status({ scope: 'local' });
    assert.equal(actual.configuration, 'applied', '仅注释或换行不同不应显示待生效');
    await page.route('**/api/status?scope=local', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ ...actual, configuration: 'pending' }) }), { times: 1 });
    await page.locator('#refresh-status').click();
    await button.waitFor();
    await button.click();
    await page.waitForFunction(() => document.getElementById('pending-config-note').textContent.includes('参数值一致'));
    assert.equal(await dialog.locator('[data-configuration-key]').count(), 0);
    await page.waitForFunction(() => document.getElementById('game-config-state').textContent === '已生效');
    await page.locator('#pending-config-done').click();
    await f.task('stop');
    const stopped = f.manager.store.snapshot();
    const stoppedProfile = stopped.workspace.profiles.find(profile => profile.id === stopped.workspace.activeId);
    stoppedProfile.source = serialize(parse(stoppedProfile.source), new Map([['ExpRate', '4']]));
    await f.manager.store.update(stopped.workspace, stopped.revision);
    await page.reload(); await button.click(); await card('ExpRate').waitFor();
    assert.equal(await value('ExpRate', 'running').count(), 0);
    await undo('ExpRate').click(); await card('ExpRate').waitFor({ state: 'detached' });
    assert.equal(Number(stored('ExpRate')), 1, '停服时恢复已写入文件的值');
    assert.equal(await dialog.locator('[data-configuration-key]').count(), 0);
    await page.locator('#pending-config-done').click();
    assert.deepEqual(errors, []);
    console.log('PASS 差异标记跟随待应用值、单项撤销到启动或文件值、保存失败重试、保留其他修改、撤销不写入游戏或重启、手机布局、密码遮挡、应用后清空及格式差异不误报');
  } finally { await browser?.close(); await f.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
